    <section>
        <h3 class="font-semibold text-gray-900">3. KEBERSIHAN DAN ALAM</h3>
        <ol class="mt-2 list-[lower-alpha] space-y-1 pl-6">
            <li>Dilarang membuang sampah sembarangan. Buang sampah di tempat yang tersedia.</li>
            <li>Dilarang merusak tanaman dan fasilitas, serta mencoret-coret tenda atau fasilitas.</li>
            <li>Dilarang membawa senjata tajam, kecuali telah mendapat izin atau untuk keperluan lain seperti memasak.</li>
            <li>Dilarang membawa alat yang dapat mencemari lingkungan, seperti pilox, cat, pestisida, dan sejenisnya.</li>
            <li>Api unggun hanya diperbolehkan di area yang disediakan dan wajib dipadamkan setelah selesai.</li>
            <li>Dilarang buang air selain di toilet yang telah disediakan.</li>
        </ol>
    </section>

